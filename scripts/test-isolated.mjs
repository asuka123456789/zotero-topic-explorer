import { spawn } from "node:child_process";
import process from "node:process";
import console from "node:console";
import { access, lstat, mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// 隔离集成测试包装器，改编自 Zotero MCP Plus 的同名脚本；只使用本项目
// .scaffold/test 下的独立 profile/data，绝不触碰主 profile 或真实文库。
// 注意：scaffold 在 Windows 上会显示 Zotero 窗口，运行前须先获得许可。

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const sandbox = join(root, ".scaffold", "test");
const marker = join(sandbox, "TOPIC_EXPLORER_TEST_SANDBOX.json");
const owner = "zotero-topic-explorer-isolated-test";
const binary = process.env.ZOTERO_PLUGIN_ZOTERO_BIN_PATH;
if (!binary)
  throw new Error(
    "请通过 ZOTERO_PLUGIN_ZOTERO_BIN_PATH 指定 Zotero 可执行文件；不猜测或使用默认 profile",
  );
if (process.env.TOPIC_EXPLORER_ALLOW_GUI !== "1")
  throw new Error(
    "集成测试会显示 Zotero 窗口；确认许可后设置 TOPIC_EXPLORER_ALLOW_GUI=1 再运行",
  );
await access(binary);
for (const path of [root, join(root, ".scaffold"), sandbox]) {
  const stat = await lstat(path).catch((error) => {
    if (error.code !== "ENOENT") throw error;
    return null;
  });
  if (stat?.isSymbolicLink()) throw new Error("隔离测试目录不能是 symlink/junction");
}
const contents = await readdir(sandbox).catch((error) => {
  if (error.code !== "ENOENT") throw error;
  return [];
});
if (contents.length) {
  const saved = JSON.parse(await readFile(marker, "utf8").catch(() => "null"));
  if (saved?.owner !== owner || saved?.version !== 1) {
    throw new Error(
      "现有 .scaffold/test 不是本测试创建的目录，拒绝清空；请检查现有内容",
    );
  }
}
for (const name of ["profile", "data", "resource"]) {
  const stat = await lstat(join(sandbox, name)).catch((error) => {
    if (error.code !== "ENOENT") throw error;
    return null;
  });
  if (stat?.isSymbolicLink()) throw new Error("测试子目录不能是 symlink/junction");
}
await mkdir(sandbox, { recursive: true });
await writeFile(marker, JSON.stringify({ owner, version: 1 }));

// scaffold 的测试资源仍从旧 chai.js URL 下载；用锁文件中的 Chai 本地生成浏览器包。
const chaiCache = join(root, ".scaffold", "cache", "chai.js");
const cachedChai = await readFile(chaiCache, "utf8").catch((error) => {
  if (error.code !== "ENOENT") throw error;
  return null;
});
const chaiMarker = "// Generated by zotero-topic-explorer isolated tests";
if (cachedChai !== null && !cachedChai.startsWith(chaiMarker)) {
  throw new Error("存在非本测试生成的 Chai 缓存，请先检查，不自动覆盖");
}
const { build } = await import("esbuild");
await build({
  stdin: {
    contents: "import * as chai from 'chai'; globalThis.chai = chai;",
    resolveDir: root,
  },
  bundle: true,
  platform: "browser",
  format: "iife",
  target: "firefox140",
  outfile: chaiCache,
  banner: { js: chaiMarker },
});
console.log(
  "仅启动 .scaffold/test/profile 与 .scaffold/test/data 隔离实例；不会停止或修改主 Zotero。",
);
const child = spawn(
  process.execPath,
  [
    join(root, "node_modules", "zotero-plugin-scaffold", "bin", "zotero-plugin.mjs"),
    "test",
    "--no-watch",
  ],
  {
    cwd: root,
    env: { ...process.env, MOZ_NO_REMOTE: "1" },
    stdio: "inherit",
  },
);
child.on("error", (error) => {
  console.error(error.message);
  process.exitCode = 1;
});
child.on("exit", async (code) => {
  process.exitCode = code ?? 1;
  try {
    const result = JSON.parse(
      await readFile(join(sandbox, "data", "topic-explorer-result.json"), "utf8"),
    );
    if (result.total < 6 || result.passed !== result.total || result.failed !== 0)
      throw new Error("topic-explorer-result.json: 测试未全部通过");
    // 可选的真实模型联调结果：存在时打印摘要，不影响退出码。
    const live = await readFile(
      join(sandbox, "data", "topic-explorer-live-result.json"),
      "utf8",
    ).catch(() => null);
    if (live) {
      const summary = JSON.parse(live);
      console.log(
        `联调结果：enabled=${summary.enabled} state=${summary.state} requests=${summary.requestsUsed}`,
      );
      for (const step of summary.usage ?? []) {
        console.log(
          `  ${step.step}: ${step.state} in=${step.inputTokens} out=${step.outputTokens} ${step.durationMs ?? "?"}ms${step.error ? ` ${step.error}` : ""}`,
        );
      }
    }
  } catch (error) {
    console.error(`集成验证未完成：${error.message}`);
    process.exitCode = 1;
  }
});
